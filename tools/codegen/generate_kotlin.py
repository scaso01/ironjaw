#!/usr/bin/env python3
"""Generate Kotlin data classes and RPC method stubs from Ironjaw schema.

Reads the JSON schema produced by extract_schema.py and generates
a Kotlin file with method constants and typed request builders.

Usage:
    python extract_schema.py | python generate_kotlin.py > IronjawProtocol.kt

Or with a schema file:
    python generate_kotlin.py schema.json > IronjawProtocol.kt
"""
import json
import sys
from datetime import datetime, timezone


def to_kotlin_name(method: str) -> str:
    """Convert 'cc.chat.abort' to 'ccChatAbort'."""
    parts = method.replace(".", "_").split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def to_kotlin_const(method: str) -> str:
    """Convert 'cc.chat.abort' to 'CC_CHAT_ABORT'."""
    return method.replace(".", "_").upper()


def generate(schema: dict) -> str:
    """Generate Kotlin source from schema."""
    methods = schema["methods"]
    categories = {}
    for m in methods:
        cat = m["category"]
        if cat not in categories:
            categories[cat] = []
        categories[cat].append(m)

    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    lines = [
        "package com.scaso.drclawapp.data.websocket",
        "",
        "// ---------------------------------------------------------------------",
        f"// AUTO-GENERATED by ironjaw codegen -- {now}",
        "// Do not edit manually. Regenerate with:",
        "//   cd ironjaw/tools/codegen",
        "//   python extract_schema.py | python generate_kotlin.py > IronjawProtocol.kt",
        "// ---------------------------------------------------------------------",
        "",
        "import kotlinx.serialization.json.JsonElement",
        "import kotlinx.serialization.json.buildJsonObject",
        "import kotlinx.serialization.json.put",
        "",
        "/**",
        " * Ironjaw RPC method constants and typed request builders.",
        f" * Generated from {len(methods)} methods across {len(categories)} categories.",
        " */",
        "object IronjawProtocol {",
        "",
        "    // -- Method Constants -------------------------------------------",
        "",
    ]

    for cat, cat_methods in sorted(categories.items()):
        lines.append(f"    // {cat}")
        for m in cat_methods:
            const = to_kotlin_const(m["method"])
            lines.append(f'    const val {const} = "{m["method"]}"')
        lines.append("")

    lines.extend([
        "    // -- Tier Info ----------------------------------------------------",
        "",
        "    /** Permission tier for each method (auto, notify, confirm, multiconfirm). */",
        "    val tiers: Map<String, String> = mapOf(",
    ])

    for m in methods:
        const = to_kotlin_const(m["method"])
        lines.append(f'        {const} to "{m["tier"]}",')

    lines.extend([
        "    )",
        "",
        "    // -- Request Builders ---------------------------------------------",
        "",
    ])

    # Generate typed builder functions for common methods
    builders = {
        "cc.chat": [("sessionId", "String?", True), ("message", "String", True), ("thinkingLevel", "String?", False)],
        "cc.sessions": [],
        "cc.session.get": [("sessionId", "String", True)],
        "cc.history": [("sessionId", "String", True), ("limit", "Int?", False)],
        "cc.chat.abort": [("sessionId", "String", True)],
        "cc.session.create": [("cwd", "String?", False), ("role", "String?", False), ("model", "String?", False), ("project", "String?", False)],
        "cc.attach": [("sessionId", "String", True)],
        "cc.detach": [("sessionId", "String", True)],
        "chat.send": [("message", "String", True)],
        "chat.history": [("limit", "Int?", False)],
        "chat.abort": [("runId", "String?", False)],
        "model.status": [],
        "model.list": [],
        "model.switch": [("model", "String", True)],
        "infra.status": [],
        "device.list": [],
        "tts.generate": [("text", "String", True), ("voice", "String?", False)],
        "tts.voices": [],
    }

    for method_name, params in sorted(builders.items()):
        fn_name = to_kotlin_name(method_name)
        const = to_kotlin_const(method_name)

        if not params:
            lines.append(f"    /** Build params for `{method_name}` RPC. */")
            lines.append(f"    fun {fn_name}Params(): JsonElement? = null")
            lines.append("")
        else:
            param_str = ", ".join(
                f"{p[0]}: {p[1]}" + ("" if p[2] else " = null")
                for p in params
            )
            lines.append(f"    /** Build params for `{method_name}` RPC. */")
            lines.append(f"    fun {fn_name}Params({param_str}): JsonElement = buildJsonObject {{")
            for pname, ptype, required in params:
                base_type = ptype.rstrip("?")
                is_nullable = ptype.endswith("?")
                if is_nullable:
                    lines.append(f'        {pname}?.let {{ put("{pname}", it) }}')
                elif base_type == "Int":
                    lines.append(f'        put("{pname}", {pname})')
                else:
                    lines.append(f'        put("{pname}", {pname})')
            lines.append("    }")
            lines.append("")

    lines.extend([
        "    // -- Category Grouping --------------------------------------------",
        "",
        "    val categories: Map<String, List<String>> = mapOf(",
    ])

    for cat, cat_methods in sorted(categories.items()):
        method_list = ", ".join(to_kotlin_const(m["method"]) for m in cat_methods)
        lines.append(f'        "{cat}" to listOf({method_list}),')

    lines.extend([
        "    )",
        "}",
        "",
    ])

    return "\n".join(lines)


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1]) as f:
            schema = json.load(f)
    else:
        schema = json.load(sys.stdin)

    print(generate(schema))


if __name__ == "__main__":
    main()
